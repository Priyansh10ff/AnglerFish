// Builds the pre-filled cybercrime.gov.in complaint text from case evidence.
import type { CaseState } from "./types";
import { mergedIdentifiers } from "./evidence";

const list = (xs: string[]) => (xs.length ? xs.join(", ") : "none found");

export function buildComplaint(c: CaseState): string {
  const r = c.recon.result;
  const b = c.bait.result;
  const ids = mergedIdentifiers(c);

  if (c.verdict === "legit") {
    return `NO COMPLAINT GENERATED
(Anglerfish assessment, case ${c.id}, ${new Date(c.createdAt).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST)

${c.targetUrl ?? c.input}

Recon found no fraud indicators (confidence: ${r?.confidence ?? "unknown"}).
${r?.verdict_reason ?? r?.page_summary ?? ""}

No bait run was performed and no report is filed for a site assessed as legitimate.
If you believe this is wrong, re-run with the exact page where the scam appeared (payment or login step), not the homepage.`;
  }

  const scamType = r?.scam_type?.trim() || "Suspected phishing / financial fraud";
  const brand = r?.brand_impersonated?.trim();
  const related = c.mapper.sites.map((s) => `${s.url} (shares: ${s.matchedOn.join(", ")})`);

  const subjectLabel =
    c.inputType === "upi" ? "SUSPECT UPI ID" : c.inputType === "phone" ? "SUSPECT PHONE NUMBER" : "SUSPECT WEBSITE / CONTACT";

  return `COMPLAINT — Online Financial Fraud / Phishing
(prepared with Anglerfish on ${new Date(c.createdAt).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST; submit at https://cybercrime.gov.in)

1. ${subjectLabel}
${c.targetUrl ?? c.input}

2. NATURE OF FRAUD
${scamType}${brand ? `, impersonating ${brand}` : ""}.${c.verdict === "suspicious" ? " (Assessment: suspicious — fraud indicators present but not conclusive.)" : ""}
${r?.verdict_reason?.trim() ?? ""}
${r?.page_summary?.trim() ?? ""}

3. HOW THE FRAUD OPERATES
${
  b?.form_found
    ? `The site collects victim details through a form. After submission${b.next_page_summary ? `: ${b.next_page_summary}` : ", a hidden next step is shown."}`
    : c.targetUrl
      ? "The page solicits victims directly without a lead-capture form."
      : "The identifier above was used to solicit or collect fraudulent payments."
}
${b?.payment_requested ? `Payment demanded: ${b.payment_requested}` : ""}
${c.targetUrl ? "This was established in an isolated investigation browser using only fictitious test data; no real personal or payment information was submitted." : ""}

4. PAYMENT / CONTACT IDENTIFIERS USED BY THE SUSPECTS
UPI IDs: ${list(ids.upi_ids)}
Phone / WhatsApp numbers: ${list(ids.phone_numbers)}
Telegram handles: ${list(ids.telegram_handles)}
Email addresses: ${list(ids.emails)}
Bank accounts: ${list(ids.bank_accounts)}

5. RELATED WEBSITES (same operation — shared identifiers, template or hosting)
${related.length ? related.map((x) => `- ${x}`).join("\n") : "- none identified yet"}

6. EVIDENCE
Evidence dossier generated by Anglerfish (case ${c.id}) is attached${
    c.recon.steps.length + c.bait.steps.length > 0
      ? `, including ${c.recon.steps.length + c.bait.steps.length} screenshots captured step-by-step in an isolated browser session`
      : ""
  }.

I request that the above ${c.targetUrl ? "website and " : ""}payment identifiers be investigated and blocked.`
    .replace(/\n{3,}/g, "\n\n");
}
