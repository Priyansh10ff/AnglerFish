// Builds the pre-filled cybercrime.gov.in complaint text from case evidence.
import type { CaseState } from "./types";

const list = (xs: string[]) => (xs.length ? xs.join(", ") : "none found");

export function buildComplaint(c: CaseState): string {
  const r = c.recon.result;
  const b = c.bait.result;
  const upi = [...new Set([...(r?.upi_ids ?? []), ...(b?.upi_ids ?? [])])];
  const phones = [...new Set([...(r?.phone_numbers ?? []), ...(b?.phone_numbers ?? [])])];
  const tg = [...new Set([...(r?.telegram_handles ?? []), ...(b?.telegram_handles ?? [])])];
  const emails = [...new Set([...(r?.emails ?? []), ...(b?.emails ?? [])])];
  const related = c.mapper.sites.map((s) => `${s.url} (shares: ${s.matchedOn.join(", ")})`);

  return `COMPLAINT — Online Financial Fraud / Phishing Website
(prepared with Anglerfish on ${new Date(c.createdAt).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST; submit at https://cybercrime.gov.in)

1. SUSPECT WEBSITE / CONTACT
${c.targetUrl ?? c.input}

2. NATURE OF FRAUD
${r?.scam_type ?? "Suspected phishing / financial fraud"}${r?.brand_impersonated ? `, impersonating ${r.brand_impersonated}` : ""}.
${r?.page_summary ?? ""}

3. HOW THE FRAUD OPERATES
${b?.form_found ? `The site collects victim details through a form. After submission${b.next_page_summary ? `: ${b.next_page_summary}` : ", a hidden next step is shown."}` : "The site presents fraudulent content directly."}
${b?.payment_requested ? `Payment demanded: ${b.payment_requested}` : ""}
This was established in an isolated investigation browser using only fictitious test data; no real personal or payment information was submitted.

4. PAYMENT / CONTACT IDENTIFIERS USED BY THE SUSPECTS
UPI IDs: ${list(upi)}
Phone / WhatsApp numbers: ${list(phones)}
Telegram handles: ${list(tg)}
Email addresses: ${list(emails)}

5. RELATED WEBSITES (same operation — shared identifiers, template or hosting)
${related.length ? related.map((x) => `- ${x}`).join("\n") : "- none identified yet"}

6. EVIDENCE
Screenshots and the recorded browsing session are attached as a dossier PDF generated by Anglerfish (case ${c.id}).

I request that the above website and payment identifiers be investigated and blocked.`;
}
